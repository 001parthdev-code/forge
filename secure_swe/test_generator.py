def generate_security_test(
    finding: SecurityFinding,
    plan: RemediationPlan,
    patch: AppliedPatch,
    inventory: RepoInventory,
) -> tuple[SecurityRegressionTest, DesiredOutcome]:
    """
    Generate a behavioral security regression test and desired outcome for a
    successfully applied command-injection remediation.

    Parameters
    ----------
    finding:
        The SecurityFinding that initiated the remediation chain.
    plan:
        The RemediationPlan derived from *finding*.
    patch:
        The AppliedPatch produced from *plan*.  Must have applied=True.
    inventory:
        The RepoInventory snapshot used during earlier analysis stages.

    Returns
    -------
    tuple[SecurityRegressionTest, DesiredOutcome]
        Both artifacts share the same finding_id for full chain traceability.

    Raises
    ------
    TraceabilityError
        When finding → plan → patch IDs are inconsistent or patch.applied
        is False.
    GenerationError
        When a safe behavioral test cannot be constructed (unsupported
        vulnerability type, missing source evidence, etc.).
    """
    # ------------------------------------------------------------------
    # 1. Validate traceability chain
    # ------------------------------------------------------------------
    _validate_chain(finding, plan, patch)

    # ------------------------------------------------------------------
    # 2. Guard: only command_injection is supported in this vertical slice
    # ------------------------------------------------------------------
    if finding.vulnerability_type not in _SUPPORTED_VULNERABILITY_TYPES:
        raise GenerationError(
            f"Vulnerability type '{finding.vulnerability_type}' is not "
            f"supported by the v0 test generator.  "
            f"Only {sorted(_SUPPORTED_VULNERABILITY_TYPES)} are handled."
        )

    # ------------------------------------------------------------------
    # 3. Retrieve source evidence from inventory
    # ------------------------------------------------------------------
    source = _get_source(inventory, finding.file)
    if source is None:
        raise GenerationError(
            f"Source content for '{finding.file}' is not available in the "
            f"inventory (file may be binary, oversized, or missing).  "
            f"Cannot construct a behavioral test without source evidence."
        )

    # ------------------------------------------------------------------
    # 4. Infer function name and module path
    # ------------------------------------------------------------------
    function_name = _infer_function_name(source, finding.line)
    if function_name is None:
        raise GenerationError(
            f"Cannot determine the function enclosing line {finding.line} "
            f"in '{finding.file}'.  "
            f"A top-level expression or parse error prevents test generation."
        )

    module_path = _infer_module_path(finding.file)

    # ------------------------------------------------------------------
    # 5. Build the test function name and file path
    # ------------------------------------------------------------------
    test_name = f"test_{function_name}_rejects_shell_metacharacters"
    test_file = _derive_test_file_path(finding.file, function_name)

    # ------------------------------------------------------------------
    # 6. Build behavioral test code
    # ------------------------------------------------------------------
    test_code = _build_subprocess_list_test(
        module_path=module_path,
        function_name=function_name,
        test_name=test_name,
        sentinel=_SENTINEL_INPUT,
        sink=finding.sink,
    )

    # ------------------------------------------------------------------
    # 7. Assemble SecurityRegressionTest
    # ------------------------------------------------------------------
    regression_test = SecurityRegressionTest(
        test_id=_test_id(patch.patch_id),
        finding_id=finding.id,
        plan_id=plan.plan_id,
        patch_id=patch.patch_id,
        target_file=finding.file,
        test_file=test_file,
        test_name=test_name,
        security_property=(
            "Dynamic/untrusted values must remain data and must not be "
            "interpreted as shell syntax."
        ),
        test_code=test_code,
        expected_behavior=(
            f"Calling {function_name}() with the adversarial sentinel input "
            f"{repr(_SENTINEL_INPUT)} must result in the value being passed as "
            f"a discrete argument list element, not as part of a shell string.  "
            f"shell=True must be absent from the remediated call."
        ),
    )

    # ------------------------------------------------------------------
    # 8. Assemble DesiredOutcome
    # ------------------------------------------------------------------
    desired_outcome = DesiredOutcome(
        outcome_id=_outcome_id(finding.id),
        finding_id=finding.id,
        security_invariants=list(_SECURITY_INVARIANTS),
        regression_requirements=list(_REGRESSION_REQUIREMENTS),
        verification_requirements=list(_VERIFICATION_REQUIREMENTS),
    )

    logger.info(
        "Generated security regression test '%s' for finding '%s'.",
        regression_test.test_id,
        finding.id,
    )

    return regression_test, desired_outcome


def persist_security_test(
    test: SecurityRegressionTest,
    repo_path: str | os.PathLike,
) -> Path:
    """
    Write the generated test code to disk inside *repo_path*.

    Safety checks
    -------------
    * The destination path must resolve inside *repo_path* (no traversal).
    * The parent directory is created if it does not exist.
    * If a file already exists at the path and its content matches the
      generated test, the write is skipped (idempotent).
    * If a file exists with *different* content, writing is refused unless
      the existing file is also a generated security test (identified by
      the generated header comment).  This prevents silently overwriting
      unrelated tests.

    Parameters
    ----------
    test:
        A SecurityRegressionTest produced by generate_security_test().
    repo_path:
        Absolute (or resolvable) path to the controlled repository root.

    Returns
    -------
    Path
        The absolute path to the written test file.

    Raises
    ------
    GenerationError
        On path traversal, or if the target file already exists with
        unrelated content.
    OSError
        On write failures (propagated directly).
    """
    root = Path(repo_path).resolve()

    # Path containment
    target = _safe_test_file_path(test.test_file, root)

    # Create parent directories if needed.
    target.parent.mkdir(parents=True, exist_ok=True)

    # Idempotency and conflict detection.
    if target.exists():
        existing = target.read_text(encoding="utf-8")
        if existing == test.test_code:
            logger.debug("Test file '%s' already up to date; skipping write.", target)
            return target
        # Allow overwrite only if the existing file looks like a previously
        # generated security test (contains the generator header comment).
        if "Generated by secure_swe.test_generator." not in existing:
            raise GenerationError(
                f"File '{target}' already exists and does not appear to be a "
                f"previously generated security test.  Refusing to overwrite."
            )

    target.write_text(test.test_code, encoding="utf-8")
    logger.info("Wrote security regression test to '%s'.", target)
    return target
